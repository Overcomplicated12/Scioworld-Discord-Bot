import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {verifyDiscussionLink,ensureDiscussionThread} from '../src/discussion-links.js';
import {handleInteraction,activityMessage} from '../src/commands/weekly.js';
import {createStore} from '../src/store.js';
const now=Date.now();
const activity={id:'a',threadId:'200',opensAt:now-1000,closesAt:now+1000,prompt:'Test',choices:['a','b'],format:'discussion'};
const message={id:'300',author:{id:'alice',bot:false},createdTimestamp:now,system:false};
const thread={id:'200',isThread:()=>true,messages:{fetch:async()=>message}};
const guild={id:'100',channels:{fetch:async()=>thread}};
const url='https://discord.com/channels/100/200/300';
const verified=await verifyDiscussionLink(guild,'alice',url,activity,now+2000);
assert.equal(verified.authorId,'alice');
await assert.rejects(()=>verifyDiscussionLink(guild,'bob',url,activity,now+2000),/own discussion/);
await assert.rejects(()=>verifyDiscussionLink(guild,'alice',url.replace('/200/','/201/'),activity,now+2000),/this question/);
await assert.rejects(()=>verifyDiscussionLink(guild,'alice',url.replace('/100/','/101/'),activity,now+2000),/this question/);
await assert.rejects(()=>verifyDiscussionLink(guild,'alice',url,activity,now-1),/during/);
await assert.rejects(()=>verifyDiscussionLink({...guild,channels:{fetch:async()=>{throw Error('gone');}}},'alice',url,activity,now+2000),/unavailable/);
assert.equal(await ensureDiscussionThread({thread:{id:'200'}},null,{}),'200');
assert.equal(await ensureDiscussionThread({id:'200',startThread:async()=>{throw {code:160004};}},{guild},{}),'200');
const payload=activityMessage({guildId:'100',season:'test',activity},now);
assert.equal(payload.components[1].components[0].toJSON().url,'https://discord.com/channels/100/200');
let modal;
await handleInteraction({guildId:'100',user:{id:'alice'},customId:'weekly:link:test:a',showModal:async v=>{modal=v.toJSON();}});
assert(modal.components[0].components[0].label.length<=45);
let saved,reply;
await handleInteraction({guildId:'100',guild,user:{id:'alice'},customId:modal.custom_id,isModalSubmit:()=>true,fields:{getTextInputValue:()=>url},deferReply:async()=>{},editReply:async v=>{reply=v;}},{pilot:(g,u,action,args)=>{if(action==='weekly')return {activity,seasonEnd:now+2000};saved=args;return {saved:true};}});
assert.equal(saved.sourceMessage.url,url);
assert.match(reply.content,/review queue/);
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'scio-public-'));
try{
 const store=createStore(path.join(dir,'data.json'));
 store.getOrCreate('100','alice');
 const config=JSON.parse(fs.readFileSync(new URL('../content/pilot/season.json',import.meta.url)));
 store.pilot('100','admin','create',{config,start:new Date(now-1000).toISOString(),channelId:'channel'},now,true);
 store.pilot('100','admin','activate',{},now,true);
 const job=store.getPilotJobs('100',now)[0];job.activity.threadId='200';store.ackPilotJob('100',job,'post');
 store.pilot('100','alice','discuss',{activity:job.activity.id,sourceMessage:verified,text:'Public message: '+url},now);
 assert.throws(()=>store.pilot('100','alice','discuss',{activity:job.activity.id,text:'Private second submission'},now),/already submitted/);
 store.pilot('100','admin','review',{id:'D1',decision:'approved',reason:'Meaningful explanation'},now,true);
 store.pilot('100','admin','review',{id:'D1',decision:'approved',reason:'Retry'},now,true);
 assert.equal(store.pilot('100','alice','passport',{},now).stamps,1);
 assert.equal(store.pilot('100','alice','weekly',{},now).discussion.sourceMessage.url,url);
 console.log('Public discussion checks passed: modal, link ownership, guild/thread scope, timestamps, unavailable messages, recovery, and shared reward cap.');
}finally{fs.rmSync(dir,{recursive:true,force:true});}
