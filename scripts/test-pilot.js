import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createStore } from '../src/store.js';
import { DAY, validatePilot } from '../src/pilot.js';
const config = JSON.parse(fs.readFileSync(new URL('../content/pilot/season.json', import.meta.url)));
config.activities = config.activities.slice(0, 2);
config.activities[0].openDay = 0; config.activities[0].closeDay = 5;
config.activities[1].openDay = 7; config.activities[1].closeDay = 12;
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'scio-pilot-'));
try {
  const file = path.join(dir, 'profiles.json');
  let store = createStore(file);
  const start = Date.UTC(2030, 0, 1);
  const g = 'guild';
  for (const id of ['alice','bob','admin']) store.getOrCreate(g, id);
  const call = (action, args = {}, at = start, id = 'admin') => store.pilot(g, id, action, args, at, id === 'admin');
  assert.throws(() => call('create', { config, start: new Date(start).toISOString(), channelId: 'channel' }, start, 'alice'), /Only/);
  call('create', { config, start: new Date(start).toISOString(), channelId: 'channel' });
  assert(fs.existsSync(`${file}.pre-pilot.bak`));
  assert.equal(call('status').status, 'draft');
  assert.equal(store.getPilotJobs(g, start).length, 0);
  assert.throws(() => call('answer', {activity: 'floating-frog', choice: 0}, start, 'alice'));
  call('activate');
  assert.equal(call('weekly').activity.correct, undefined);
  call('answer', { choice: 1 }, start, 'alice');
  call('answer', { choice: 0 }, start + 1, 'alice');
  assert.equal(call('passport', {}, start, 'alice').stamps, 1);
  assert.equal(store.getOrCreate(g,'alice').coins,100, 'Simulation must not pay real coins');
  call('discuss', {text:'Ice is less dense, so buoyancy balances its weight.'}, start, 'alice');
  call('review', {id:'D1',decision:'revision',reason:'Can you connect this to floating?'});
  call('discuss', {text:'Ice displaces enough water to balance its weight before it submerges.'}, start+1, 'alice');
  call('review', {id:'D1',decision:'approved',reason:'Clear reasoning.'});
  call('review', {id:'D1',decision:'approved',reason:'Retry.'});
  assert.equal(call('passport', {}, start, 'alice').stamps, 2);
  assert.throws(() => call('answer', { activity:'floating-frog', choice:1 }, start+5*DAY, 'alice'));
  assert.equal(call('weekly', {activity:'floating-frog'}, start+5*DAY).activity.correct,0);
  store = createStore(file);
  assert.equal(call('passport', {}, start+6*DAY,'alice').stamps,2);
  call('answer', {choice:1}, start+7*DAY,'alice');
  call('answer', {choice:0}, start+7*DAY,'bob');
  assert.equal(call('passport',{},start+7*DAY,'alice').qualified,true);
  call('claims-open', {}, start+7*DAY);
  call('claim',{},start+7*DAY,'alice'); call('claim',{},start+7*DAY,'alice');
  assert.equal(call('report',{},start+7*DAY).claims,1);
  call('claim-review',{userId:'alice',decision:'approved',reason:'Pilot test'},start+7*DAY);
  call('claim-review',{userId:'alice',decision:'fulfilled',reason:'Simulation complete'},start+7*DAY);
  assert.equal(store.getOrCreate(g,'alice').seasonStickers,undefined);
  const report=call('report',{},start+14*DAY);
  assert.equal(report.retentionPercent,100); assert.equal(report.week2,2);
  assert.equal(call('status',{},start+14*DAY).status,'closed');
  call('quiet',{enabled:true},start+14*DAY); assert.equal(store.getPilotJobs(g,start+14*DAY).length,0);
  call('quiet',{enabled:false},start+14*DAY); assert(store.getPilotJobs(g,start+14*DAY).some(j=>j.revealed));
  const bad = structuredClone(config); bad.activities[1].openDay = 1; assert.throws(()=>validatePilot(bad),/nonoverlapping/);
  const opinion=structuredClone(config); opinion.id='opinion'; opinion.activities=[opinion.discussionExample]; opinion.simulation=false; opinion.inventory=1;
  call('create',{config:opinion,start:new Date(start+20*DAY).toISOString(),channelId:'channel'},start+20*DAY);
  call('activate',{},start+20*DAY);
  call('answer',{choice:0},start+27*DAY,'alice');
  assert.equal(store.getOrCreate(g,'alice').coins,102);
  call('answer',{choice:2},start+27*DAY+1,'alice');
  assert.equal(store.getOrCreate(g,'alice').coins,102);
  call('weekly',{},start+32*DAY);
  assert.equal(store.getOrCreate(g,'alice').coins,102,'Opinion gets no correctness bonus');
  assert.throws(()=>call('claims-open',{},start+32*DAY),/published/);
  assert.equal(call('report',{},start+32*DAY).retentionPercent,null);
  console.log('Pilot checks passed: draft, authorization, revisions, unique rewards, simulation, restart, deadlines, retention, quiet mode, opinion rewards.');
} finally { fs.rmSync(dir,{recursive:true,force:true}); }
